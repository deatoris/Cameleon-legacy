/*
    delegate.cpp

    A delegate that allows the user to change integer values from the model
    using a spin box widget.
*/

#include <QtGui>

#include "CGInstanceDelegate.h"


//! [0]
ComboBoxDelegate::ComboBoxDelegate(QObject *parent)
    : QItemDelegate(parent)
{
}
//! [0]

//! [1]
QWidget *ComboBoxDelegate::createEditor(QWidget *parent,
    const QStyleOptionViewItem &/* option */,
    const QModelIndex &/* index */) const
{
    QComboBox *editor = new QComboBox(parent);
    editor->addItem("ERRO");
    editor->addItem("WARN");
    editor->addItem("INFO");
    editor->addItem("DEBG");
    editor->addItem("DOWN");
    editor->setCurrentIndex(0);
    return editor;
}
//! [1]

//! [2]
void ComboBoxDelegate::setEditorData(QWidget *editor,
                                    const QModelIndex &index) const
{
    QString value = index.model()->data(index, Qt::EditRole).toString();

    QComboBox *spinBox = static_cast<QComboBox*>(editor);
    int i = spinBox->findText(value);
    spinBox->setCurrentIndex(i);
}
//! [2]

//! [3]
void ComboBoxDelegate::setModelData(QWidget *editor, QAbstractItemModel *model,
                                   const QModelIndex &index) const
{
    QComboBox *spinBox = static_cast<QComboBox*>(editor);
    int value = spinBox->currentIndex();
    model->setData(index, spinBox->itemText(value), Qt::EditRole);
}
//! [3]

//! [4]
void ComboBoxDelegate::updateEditorGeometry(QWidget *editor,
    const QStyleOptionViewItem &option, const QModelIndex &/* index */) const
{
    editor->setGeometry(option.rect);
}
//! [4]
